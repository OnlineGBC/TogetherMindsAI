"""
clinical_summary.py
-------------------
Therapist-only, on-demand summary of a session for the licensed clinician.

Produces three parts, all private to the therapist (the client never sees them
through the system):

  1. clinical        — a detailed clinical recap for the therapist.
  2. codes_rationale — a short note on which of the ICD codes that ALREADY
                       surfaced in-session best fit, framed as decision support
                       for billing/coding — never a diagnosis or a determination.
  3. client_recap    — a warm, plain-language recap the therapist MAY choose to
                       hand to the client; contains no codes. The system never
                       delivers it — handover is entirely the therapist's choice.

Each part is generated by its OWN Claude call returning PLAIN TEXT (no JSON).
This is deliberate:

  * No JSON parsing — the previous single combined call returned one JSON object,
    so any truncation or stray prose lost ALL THREE parts silently. Plain text
    per field removes that whole failure class.
  * Independent token budgets — each short field easily fits under max_tokens,
    so the long combined output can no longer be cut off mid-structure.
  * Partial results — if one field's call fails, the others still succeed.

Never raises — each call catches its own failure and returns "" so the caller
(console request or transcript download) always completes. Failures are LOGGED
(no longer silent). The surfaced codes themselves are deterministic (read from
the corpus via the persisted cards), so they are shown even when a narrative is
absent.
"""

import logging

import config
from ai_therapist import _get_claude_client, claude_create, claude_text

logger = logging.getLogger(__name__)

__all__ = ["generate", "generate_ehr_brief", "DISCLAIMER", "EHR_REVIEW_LINE"]

# The full clinical summary is an infrequent, on-demand, quality-sensitive call. It
# uses the app's SMART model (config.CLAUDE_MODEL_SMART, Sonnet 5.5; it was Opus 4.8
# until 2026-10-25 — check a few real summaries if you change it again). The short
# EHR chart summary uses the FAST model instead.
SUMMARY_MODEL = config.CLAUDE_MODEL_SMART

# Per-field output ceiling. Each field is only a few paragraphs, so this leaves
# ample headroom; a call that still hits it is logged (see _call) rather than
# silently truncated.
MAX_TOKENS = 6000

DISCLAIMER = (
    "Therapist-only. AI-generated decision support — not a diagnosis and not a "
    "billing or coding determination. The clinician's professional judgment governs."
)

_GROUNDING = (
    "Ground everything strictly in the transcript. Do not invent events, quotes, "
    "or codes. The transcript labels each turn \"Therapist:\", \"Client:\", or \"AI:\". "
    "Output PLAIN TEXT only — no markdown, no headings, no JSON, no preamble, no sign-off."
)

_CLINICAL_SYSTEM = (
    "You are a clinical documentation assistant writing a PRIVATE, therapist-only "
    "clinical recap of a single therapy session. Only the licensed clinician sees it.\n\n"
    "Write a detailed clinical recap: the presenting concern, the key themes, the "
    "emotional arc of the session, any risk or safety signals, and possible next steps "
    "or things to follow up. A few short paragraphs.\n\n"
    "READING LEVEL: write at an 8th-grade reading level. Short sentences (about 15-20 "
    "words). Everyday words. One idea per sentence. Active voice. Keep a clinical term "
    "when it is the precise word (catastrophizing, rumination, dissociation), but add a "
    "few plain words straight after it - e.g. \"possible catastrophizing - jumping to the "
    "worst outcome\". Detail and accuracy still come first; plain wording is how you say "
    "it, not permission to say less. Never pad to sound clinical.\n\n" + _GROUNDING
)

_CODES_SYSTEM = (
    "You are a clinical documentation assistant. A list of reference ICD codes that "
    "ALREADY surfaced during the session is provided.\n\n"
    "Write a brief note on which of THOSE codes (and only those) best fit the material, "
    "and why — a sentence or two each. Frame it explicitly as decision support for "
    "billing/coding consideration — NOT a diagnosis and NOT a billing determination. "
    "Never introduce a code that is not in the provided list. If no codes are provided, "
    "output nothing at all.\n\n"
    "READING LEVEL: write at an 8th-grade reading level. Short sentences (about 15-20 "
    "words). Everyday words. Active voice. Name the code, then say in plain words what it "
    "covers and why the session material fits it.\n\n" + _GROUNDING
)

_CLIENT_RECAP_SYSTEM = (
    "You are writing a warm, plain-language recap addressed directly to the client "
    "(\"Today we talked about ...\") that the therapist MAY choose to share. It is never "
    "delivered automatically.\n\n"
    "Cover, in a few short paragraphs: what you discussed and why it seems to matter to "
    "them; the main feelings and concerns they shared, reflected back with empathy; any "
    "strengths, insights, or helpful reframes that came up; the concrete next steps, ideas, "
    "or things to try that were agreed or suggested; and a brief encouraging close. Use "
    "supportive, validating, everyday language — NO diagnoses, NO ICD/DSM codes, no clinical "
    "jargon. Be specific to THIS conversation, not generic.\n\n" + _GROUNDING
)


def _call(system_prompt: str, user_content: str, label: str, max_tokens: int = MAX_TOKENS,
          model: "str | None" = None) -> str:
    """Make one plain-text summary call. Returns the text, or "" on failure.

    Never raises. Logs on API failure and on hitting the token ceiling (so a
    truncated field is visible in logs rather than silently cut off).
    """
    try:
        client = _get_claude_client()
        response = claude_create(
            client,
            model=model or SUMMARY_MODEL,
            max_tokens=max_tokens,
            system=system_prompt,
            messages=[{"role": "user", "content": user_content}],
        )
    except Exception as exc:
        logger.warning("Clinical summary '%s' call failed (%s); field omitted.", label, exc)
        return ""

    if getattr(response, "stop_reason", None) == "max_tokens":
        logger.warning(
            "Clinical summary '%s' hit the %d-token ceiling — output may be truncated.",
            label, max_tokens,
        )

    # First TEXT block (a thinking block may come first); "" for an empty reply
    # such as a refusal.
    return claude_text(response)


_EHR_BRIEF_SYSTEM = (
    "You are a clinical documentation assistant. Summarize one session for the "
    "clinician to file in the patient's medical chart. Report what the transcript "
    "contains; the clinician decides what it means.\n\n"
    "Rules:\n"
    "- Be specific. Name the actual topics and details that came up, including ones "
    "that seem unrelated to therapy (news, advertisements, everyday chat). Never leave "
    "a topic out because it seems off-topic: that judgment belongs to the clinician.\n"
    "- Positive judgments are welcome; negative ones are not. Never criticize, doubt, "
    "or judge the patient, the clinician, or the session. Do not use words such as "
    "unrelated, irrelevant, off-topic, poor, or wasted.\n"
    "- Open with a warm, positive framing of the session when the transcript supports "
    "it (for example, a relaxed, wide-ranging conversation, or a conversation that may "
    "have helped create a comfortable setting).\n"
    "- Describe what people did with positive or neutral verbs: the clinician shared, "
    "discussed, or talked about a topic; the group chatted about it. Avoid wording that "
    "sounds like criticism of what someone did or how much of the session it filled: "
    "do not use \"almost entirely\", \"mostly\", \"only\", \"just\", \"merely\", or "
    "\"reading\".\n"
    "- Say plainly whether a risk or safety signal was identified (or that none was "
    "identified), whether next steps were agreed (or that none were recorded), and "
    "whether it was a group session. If the conversation did not include discussion of "
    "the patient's concerns, mood, or treatment goals, say so once, as a plain fact, "
    "without judgment words.\n"
    "- Refer to the person only as \"the patient\". Do not quote at length, give a "
    "diagnosis, or name a code. Do not add a closing review reminder; one is added "
    "for you.\n"
    "- Write at an 8th-grade reading level in plain sentences, in one paragraph of "
    "up to about 200 words.\n\n" + _GROUNDING
)

# The standing last line of every chart note. Added by the code, not the model, so it
# is always there and always worded the same.
EHR_REVIEW_LINE = "The transcript should be reviewed for accuracy before filing."


def generate_ehr_brief(transcript: str, mode: str = "solo") -> str:
    """A short plain-text session summary for an EHR chart note, from the FAST model.

    "" when there is no transcript or the call failed. Never raises. The full
    analysis stays in TogetherMindsAI; the note links to it."""
    if not transcript or not transcript.strip():
        return ""
    return _call(
        _EHR_BRIEF_SYSTEM,
        f"Session type: {mode}.\n\nTranscript (speaker-labelled):\n{transcript}"
        "\n\nWrite the chart summary now.",
        label="ehr_brief", max_tokens=800, model=config.CLAUDE_MODEL_FAST,
    )


def generate(transcript: str, surfaced_codes: list, mode: str = "solo") -> "dict | None":
    """Return {clinical, codes_rationale, client_recap} for the session, or None.

    Each field is produced by its own plain-text Claude call and is "" if that
    call failed. Returns None only when there is no transcript to summarise.
    `surfaced_codes` is a list of dicts with at least "label", "code", "source" —
    the ICD entries that actually appeared in-session. Never raises.
    """
    if not transcript or not transcript.strip():
        return None

    base = f"Session type: {mode}.\n\nTranscript (speaker-labelled):\n{transcript}"

    clinical = _call(
        _CLINICAL_SYSTEM,
        base + "\n\nWrite the clinical recap now.",
        label="clinical",
    )

    if surfaced_codes:
        code_lines = "\n".join(
            f"- {c.get('label', '?')}: {c.get('code', '')} ({c.get('source', '')})"
            for c in surfaced_codes
        )
        codes_rationale = _call(
            _CODES_SYSTEM,
            base
            + "\n\nICD reference codes that surfaced during this session:\n"
            + code_lines
            + "\n\nWrite the codes rationale now.",
            label="codes_rationale",
        )
    else:
        codes_rationale = ""

    client_recap = _call(
        _CLIENT_RECAP_SYSTEM,
        base + "\n\nWrite the client recap now.",
        label="client_recap",
    )

    return {
        "clinical": clinical,
        "codes_rationale": codes_rationale,
        "client_recap": client_recap,
    }
